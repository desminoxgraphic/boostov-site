"""Build responsive images for public/products.

Source photos live in assets/products-src/<name>.(jpg|png|webp). For each one this writes
public/products/<name>-<width>.(avif|webp) at the widths below (never upscaled) and regenerates
lib/images.generated.ts with dimensions and a tiny blur placeholder.

Run: python scripts/build-images.py
"""
import base64, io, json, pathlib
from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "assets" / "products-src"
OUT = ROOT / "public" / "products"
WIDTHS = [320, 480, 640, 828, 1080, 1280]
# Per-image width cap (kit photo is low resolution until the real one arrives).
MAX = {"kit-cards": 500}

manifest = {}
for f in sorted(SRC.iterdir()):
    if f.suffix.lower() not in {".jpg", ".jpeg", ".png", ".webp"}:
        continue
    name = f.stem
    im = Image.open(f)
    im = im.convert("RGBA") if im.mode in ("RGBA", "LA", "P") else im.convert("RGB")
    cap = min(im.width, MAX.get(name, im.width))
    widths = sorted({w for w in WIDTHS if w <= cap} | {cap})
    for w in widths:
        h = round(im.height * w / im.width)
        r = im.resize((w, h), Image.LANCZOS)
        r.save(OUT / f"{name}-{w}.webp", "WEBP", quality=78, method=6)
        r.save(OUT / f"{name}-{w}.avif", "AVIF", quality=55, speed=4)
    tiny = im.copy()
    tiny.thumbnail((16, 16))
    buf = io.BytesIO()
    tiny.save(buf, "WEBP", quality=40)
    manifest[name] = {
        "width": cap,
        "height": round(im.height * cap / im.width),
        "widths": widths,
        "alpha": im.mode == "RGBA",
        "blur": "data:image/webp;base64," + base64.b64encode(buf.getvalue()).decode(),
    }

ts = "// Generated by scripts/build-images.py. Do not edit by hand.\n"
ts += "export const IMAGES = " + json.dumps(manifest, indent=2) + " as const;\n"
ts += "export type ImageName = keyof typeof IMAGES;\n"
(ROOT / "lib" / "images.generated.ts").write_text(ts, encoding="utf-8")
print({k: (v["width"], v["height"], v["widths"]) for k, v in manifest.items()})
